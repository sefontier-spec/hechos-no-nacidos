-- =============================================================================
-- Esquema SQL Ligero para Supabase — «Hechos, no nacidos / Made, Not Born»
-- =============================================================================
-- Ejecute este script en el SQL Editor de su proyecto gratuito de Supabase
-- si desea sincronizar los votos y actas globalmente entre todos los lectores.

create table if not exists public.step_votes (
  id bigint generated by default as identity primary key,
  selected_step text not null,
  lang text default 'es',
  created_at timestamptz default now()
);

create table if not exists public.bracket_votes (
  id bigint generated by default as identity primary key,
  article_id text not null,
  option_key text not null,
  lang text default 'es',
  created_at timestamptz default now()
);

create table if not exists public.objections (
  id bigint generated by default as identity primary key,
  target text not null,
  alias text default 'Lector anónimo',
  comment_text text not null check (char_length(comment_text) between 25 and 1800),
  lang text default 'es',
  created_at timestamptz default now()
);

-- Habilitar Row Level Security (RLS) con lectura y envío público anónimo
alter table public.step_votes enable row level security;
alter table public.bracket_votes enable row level security;
alter table public.objections enable row level security;

create policy "Permitir lectura pública de votos de pasos"
  on public.step_votes for select to anon using (true);
create policy "Permitir inserción pública de votos de pasos"
  on public.step_votes for insert to anon with check (true);

create policy "Permitir lectura pública de votos de corchetes"
  on public.bracket_votes for select to anon using (true);
create policy "Permitir inserción pública de votos de corchetes"
  on public.bracket_votes for insert to anon with check (true);

create policy "Permitir lectura pública de actas y objeciones"
  on public.objections for select to anon using (true);
create policy "Permitir inserción pública de actas y objeciones"
  on public.objections for insert to anon with check (char_length(comment_text) >= 25);
